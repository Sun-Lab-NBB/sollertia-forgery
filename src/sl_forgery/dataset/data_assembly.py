def _add_fluorescence_column(
    df: pl.DataFrame, data_path: Path, filename: str, column_name: str, cell_mask: None | bool | NDArray[np.bool] = None
) -> pl.DataFrame:
    """Updates the input dataframe with the requested fluorescence data column and returns it back to caller.

    This helper function is used by the main assemble_mesoscope_data() function to streamline loading the data from
    different arrays generated by the sl-suite2p single-day and multi-day pipelines.

    Args:
        df: The Polars dataframe to add the column to.
        data_path: The path to the directory that stores the data to be added.
        filename: The name of the .npy file that stores the data to be added.
        column_name: The name of the column under which to add the extracted data.
        cell_mask: The optional boolean mask to filter out non-cell objects.

    Returns:
        The dataframe with the new column added.
    """

    # Extracts the data using memory-mapping.
    fluorescence = np.load(data_path.joinpath(filename), mmap_mode="r")

    # Applies the cell mask if provided
    if cell_mask is not None:
        fluorescence = fluorescence[cell_mask, :]

    # Gets ROI count for Array field width.
    roi_count = fluorescence.shape[0]

    # Transposes (to go from ROI, Frame to Frame, ROI) and converts to a list of lists
    # (required for conversion to the Polar Array type).
    fluorescence_lists = [row.tolist() for row in fluorescence.T.astype(np.float32)]

    # Updates the dataframe with the new column storing the extracted fluorescence data.
    return df.with_columns(
        [
            pl.Series(
                name=column_name,
                values=fluorescence_lists,
                dtype=pl.List(pl.Float32),  # Casts to float32 to match the original array's precision.
            ).list.to_array(width=roi_count)
        ]
    )


def assemble_mesoscope_data(session_data_path: Path, multiday_data_path: Path) -> pl.DataFrame:
    """Assembles all processed data acquired by the Mesoscope into a uniform DataFrame.

    This function resolves the mesoscope frame acquisition timestamps and bundles them with the processed single-day
    and multi-day fluorescence data.

    Args:
        session_data_path: The path to the processed session's processed data directory.
        multiday_data_path: The path to the processed session's directory in the dataset generated by the multiday
            sl-suite2p pipeline.

    Returns:
        The Polars DataFrame that contains the single-day and multi-day mesoscope data aligned to the acquisition time
        of each frame.
    """

    # Resolves the path to the single-day mesoscope data directory
    single_day_data = session_data_path.joinpath("processed_data", "mesoscope_data", "suite2p", "combined")

    # Resolves the path to the behavior data directory
    behavior_data = session_data_path.joinpath("processed_data", "behavior_data")

    # Queries the number of frames processed by suite2p. This is used to handle rare cases where the log has
    # more frame stamps than recorded frames, which usually happens if the user manually triggers mesoscope scanning
    # (of any kind) outside the expected time slot. Specifically, if the log has more frames than the suite2p data, the
    # log is clipped at the front (since aberrant frames have to come from a period before the main experiment runtime)
    _, frames = np.load(single_day_data.joinpath("F.npy"), mmap_mode="r").shape

    # Loads the single-day 'ops' file and extracts the scanning frequency ('fs') from the dictionary. Uses it to
    # determine the minimum and maximum scan pulse duration in milliseconds. This is used to filter the logged scan
    # pulses to match expected scan durations.
    sd_ops = np.load(single_day_data.joinpath("ops.npy"), allow_pickle=True).item()
    scanning_frequency = sd_ops["fs"]
    min_duration = 1000 / scanning_frequency - 20
    max_duration = 1000 / scanning_frequency + 20

    # Loads the mesoscope frame acquisition timestamps collected by the microcontroller logging system during session's
    # data acquisition.
    mesoscope_frame_data = pl.read_ipc(
        behavior_data.joinpath(f"mesoscope_frame_data.feather"), use_pyarrow=True, memory_map=True, rechunk=True
    )

    # Sorts by time to ensure the correct order
    mesoscope_frame_data = mesoscope_frame_data.sort("time_us")

    # Creates pulse groups and find edges in one pass
    mesoscope_frame_data = mesoscope_frame_data.with_columns(
        [
            # Creates pulse ID by counting rising edges
            (pl.col("ttl_state").diff() == 1).fill_null(False).cum_sum().alias("pulse_id"),
            # Marks if this row is a rising edge
            (pl.col("ttl_state").diff() == 1).fill_null(False).alias("is_rising_edge"),
            # Marks if this row is a falling edge
            (pl.col("ttl_state").diff() == -1).fill_null(False).alias("is_falling_edge"),
        ]
    )

    # For each pulse, finds the rising and falling-edge times using window functions
    mesoscope_frame_data = mesoscope_frame_data.with_columns(
        [
            # Gets the time of the rising edge for this pulse
            pl.when(pl.col("is_rising_edge"))
            .then(pl.col("time_us"))
            .forward_fill()
            .over("pulse_id")
            .alias("pulse_start"),
            # Gets the time of the falling edge for this pulse
            pl.when(pl.col("is_falling_edge"))
            .then(pl.col("time_us"))
            .backward_fill()
            .over("pulse_id")
            .alias("pulse_end"),
        ]
    )

    # Calculates pulse duration for each recorded scan pulse
    mesoscope_frame_data = mesoscope_frame_data.with_columns(
        [((pl.col("pulse_end") - pl.col("pulse_start")) / 1000).alias("duration_ms")]
    )

    # Filters for valid duration pulses and gets unique frames
    frame_df: pl.DataFrame = (
        mesoscope_frame_data.filter(
            (pl.col("duration_ms") >= min_duration)
            & (pl.col("duration_ms") <= max_duration)
            & pl.col("duration_ms").is_not_null()
        )
        .group_by("pulse_id")
        .first()
        .select(
            [
                pl.col("pulse_id").alias("frame"),
                pl.col("pulse_start").alias("time_us"),
            ]
        )
        .sort("frame")
    )

    # If there are more frame pulses than expected based on the processed fluorescence data, keeps only the last
    # expected_frames number of datapoints
    original_frame_count = len(frame_df)
    if original_frame_count > frames:
        frame_df = frame_df.tail(frames)  # Keeps the last 'frames' number of pulses

    # Re-assigns frame IDs starting from 1 as unsigned 32-bit integers
    frame_df = frame_df.with_columns([pl.int_range(1, len(frame_df) + 1, dtype=pl.UInt32).alias("frame")])

    # Single-Day (SD) Cell Classification:
    # Uses the cell classification data to create a filtering mask to exclude non-cells from the analysis dataset.
    classification: NDArray[np.float64] = np.load(single_day_data.joinpath("iscell.npy"), mmap_mode="r")
    is_cell_mask = classification[:, 0] == 1

    # Processes single-day data with cell filtering
    single_day_files = [
        ("F.npy", "single_day_cell_fluorescence"),
        ("Fneu.npy", "single_day_neuropil_fluorescence"),
        ("Fsub.npy", "single_day_baseline_subtracted_fluorescence"),
        ("spks.npy", "single_day_cell_spikes"),
    ]

    for filename, column_name in single_day_files:
        frame_df = _add_fluorescence_column(frame_df, single_day_data, filename, column_name, is_cell_mask)

    # Processes multi-day data (no cell filtering needed as it's pre-filtered)
    multi_day_files = [
        ("F.npy", "multi_day_cell_fluorescence"),
        ("Fneu.npy", "multi_day_neuropil_fluorescence"),
        ("Fsub.npy", "multi_day_baseline_subtracted_fluorescence"),
        ("spks.npy", "multi_day_cell_spikes"),
    ]

    for filename, column_name in multi_day_files:
        frame_df = _add_fluorescence_column(frame_df, multiday_data_path, filename, column_name, cell_mask=None)

    # Returns the assembled frame data
    return frame_df


def _add_categorical_vr_data(
    df: pl.DataFrame,
    source_data_path: Path,
) -> pl.DataFrame:
    """Converts categorical VR data columns in the target DataFrame to Categorical type, using the data from the
    appropriate experiment configuration file.

    This worker function is used by the assemble_vr_data() function to ensure categorical data columns are stored as
    appropriate pl.Categorical types.

    Args:
        df: The DataFrame to which to add the categorical VR data columns.
        source_data_path: The path to the processed session's source data folder.

    Returns:
        The DataFrame updated to include the categorical VR data columns.
    """

    # Uses the experiment configuration file to map the Mesoscope-VR trial names to their positional indices used in
    # the vr dataframe.
    experiment_config = MesoscopeExperimentConfiguration.from_yaml(
        source_data_path.joinpath("experiment_configuration.yaml")
    )
    trial_type_mapping = {i: name for i, name in enumerate(experiment_config.trial_structures.keys())}

    # Replaces the trial type columns with the categorical column that accurately reflects the trial categories
    # (as read from the experiment configuration file).
    df = df.with_columns(
        [
            pl.col("trial_type")
            .replace_strict(trial_type_mapping, default="UNKNOWN")
            .cast(pl.Categorical)
            .alias("trial_type")
        ]
    )

    return df


def assemble_vr_data(session_data_path: Path, reference_time: NDArray[np.uint64]) -> pl.DataFrame:
    """Assembles VR-related data from multiple sources and interpolates to reference timestamps.

    Args:
        session_data_path: The path to the processed session's processed data directory.
        reference_time: The time-value at which to align (interpolate) the VR data.

    Returns:
        DataFrame with columns: time_us, traveled_distance_cm, trial, trial_type, in_reward_zone, cue
    """
    behavior_data_path = session_data_path.joinpath("processed_data", "behavior_data")
    source_data_path = session_data_path.joinpath("source_data")

    # Load all data sources
    encoder_df = pl.read_ipc(behavior_data_path.joinpath("encoder_data.feather"), use_pyarrow=True)
    reward_zones_df = pl.read_ipc(behavior_data_path.joinpath("vr_reward_zone_data.feather"), use_pyarrow=True)
    cue_df = pl.read_ipc(behavior_data_path.joinpath("vr_cue_data.feather"), use_pyarrow=True)
    trial_df = pl.read_ipc(behavior_data_path.joinpath("trial_data.feather"), use_pyarrow=True)

    # Process trial data
    trial_df = trial_df.with_columns([pl.int_range(1, len(trial_df) + 1).cast(pl.UInt32).alias("trial")])

    # Start with encoder data
    vr_df = encoder_df.select(["time_us", "traveled_distance_cm"])

    # Map trial number and trial type based on distance
    vr_df = vr_df.join_asof(trial_df, on="traveled_distance_cm", strategy="backward")
    vr_df = vr_df.rename({"trial_type_index": "trial_type"})

    # Map cue based on distance
    vr_df = vr_df.join_asof(cue_df, on="traveled_distance_cm", strategy="backward").rename({"vr_cue": "cue"})

    # Calculate in_reward_zone
    in_zone_expr = pl.lit(False)
    for row in reward_zones_df.iter_rows():
        start_cm, end_cm = row[0], row[1]
        zone_condition = (pl.col("traveled_distance_cm") >= start_cm) & (pl.col("traveled_distance_cm") <= end_cm)
        in_zone_expr = in_zone_expr | zone_condition

    vr_df = vr_df.with_columns([in_zone_expr.cast(pl.UInt8).alias("in_reward_zone")])

    # Handle nulls before interpolation
    vr_df = vr_df.with_columns(
        [
            pl.col("trial").fill_null(1),
            pl.col("trial_type").fill_null(0),
            pl.col("cue").fill_null(0),
        ]
    )

    # Now interpolate to reference timestamps
    result_df = pl.DataFrame({"time_us": reference_time})

    # Define columns to interpolate and their types
    interpolation_configs = [
        ("traveled_distance_cm", False),  # continuous
        ("trial", True),  # discrete
        ("trial_type", True),  # discrete
        ("in_reward_zone", True),  # discrete
        ("cue", True),  # discrete
    ]

    for column_name, is_discrete in interpolation_configs:
        interpolated = interpolate_dataframe_data(
            df=vr_df,
            timestamp_column_name="time_us",
            value_column_name=column_name,
            seed_timestamps=reference_time,
            is_discrete=is_discrete,
        )

        result_df = result_df.join(interpolated, on="time_us", how="left")

    # After interpolation, add categorical types
    result_df = _add_categorical_vr_data(df=result_df, source_data_path=source_data_path)

    return result_df


def assemble_behavior_data(session_data_path: Path, reference_time: NDArray[np.uint64]) -> pl.DataFrame:
    """Assembles all processed data acquired by the MicroControllers into a uniform DataFrame.

    This function interpolates (aligns) all non-video behavior data acquired during the session to the 'reference_time'
    source.

    Args:
        session_data_path: The path to the processed session's processed data directory.
        reference_time: The time-value at which to align (interpolate) the behavior data.

    Returns:
        The Polars DataFrame that contains all behavior data aligned to the reference time source.
    """

    # Resolves the path to the behavior data directory
    behavior_data_path = session_data_path.joinpath("processed_data", "behavior_data")

    # Starts with the reference time as the base dataframe
    result_df = pl.DataFrame({"time_us": reference_time})

    # Defines the data extraction configuration. The values are in the order of: source file name, data column name,
    # output column name, and whether the data is discrete (True) or continuous (False).
    data_configs = [
        ("break_data.feather", "break_torque_N_cm", "break_torque_N_cm", True),
        ("encoder_data.feather", "traveled_distance_cm", "traveled_distance_cm", False),
        ("torque_data.feather", "torque_N_cm", "torque_N_cm", False),
        ("screen_data.feather", "screen_state", "screens_active", True),
        ("guidance_state_data.feather", "lick_guidance_state", "guided", True),
        ("lick_data.feather", "lick_state", "lick", True),
        ("valve_data.feather", "tone_state", "tone", True),
        ("valve_data.feather", "dispensed_water_volume_uL", "reward_volume_uL", True),
        ("trial_data.feather", "trial_type_index", "trial_type", True),
        ("trial_data.feather", "traveled_distance_cm", "trial_start_distance_cm", True),
        ("experiment_state_data.feather", "experiment_state", "experiment_stage", True),
        ("system_state_data.feather", "system_state", "system_state", True),
    ]

    # Processes each data source
    for file_name, value_col, output_col, is_discrete in data_configs:
        # Loads the data
        file_path = behavior_data_path.joinpath(file_name)
        data_df = pl.read_ipc(file_path, use_pyarrow=True)

        # Interpolates the loaded data to the reference time source
        interpolated_df = interpolate_dataframe_data(
            df=data_df,
            timestamp_column_name="time_us",
            value_column_name=value_col,
            seed_timestamps=reference_time,
            is_discrete=is_discrete,
        )

        # Joins the interpolated values to the result dataframe
        result_df = result_df.join(
            interpolated_df.select(
                [
                    pl.col("time_us"),
                    pl.col(value_col).alias(output_col),  # Renames the column if necessary
                ]
            ),
            on="time_us",
            how="left",
        )

    return result_df


